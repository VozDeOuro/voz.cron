<?php
declare(strict_types=1);

final class ImportTest extends TestCase
{
    private function oldScript(string $id, string $body = "#!/bin/bash\necho old\n"): void
    {
        $dir = Paths::$oldFlash . "/scripts/$id";
        mkdir($dir, 0777, true);
        file_put_contents("$dir/script", $body);
        file_put_contents("$dir/description", "about $id");
    }

    /** md5 of every file under $dir, to prove the old plugin's folders are never written. */
    private static function tree(string $dir): array
    {
        $out = [];
        if (!is_dir($dir)) return $out;
        $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
        foreach ($it as $f) $out[substr((string)$f, strlen($dir))] = md5_file((string)$f) . ':' . filemtime((string)$f);
        ksort($out);
        return $out;
    }

    private function config(): array { return json_decode((string)file_get_contents(Paths::configFile()), true); }

    public function testForkShapedOldDirIsCopiedAsIs(): void
    {
        $this->oldScript('nightly-backup');
        $this->oldScript('refresh-ddns');
        $cfg = ['nightly-backup' => ['frequency' => 'custom', 'custom' => '0 3 * * 1', 'overlap' => 'queue', 'timeout' => 21600], 'refresh-ddns' => ['frequency' => 'custom', 'custom' => '*/5 * * * *']];
        file_put_contents(Paths::$oldFlash . '/config.json', json_encode($cfg));
        file_put_contents(Paths::$oldFlash . '/layout.json', '{"version":3,"items":[{"type":"script","id":"refresh-ddns"},{"type":"script","id":"nightly-backup"}]}');
        file_put_contents(Paths::$oldFlash . '/settings.json', json_encode(['historyCap' => 150, 'historyDir' => Paths::$oldFlash . '/history', 'syncMinutes' => 30]));
        mkdir(Paths::$oldFlash . '/history');
        file_put_contents(Paths::$oldFlash . '/history/nightly-backup.jsonl', '{"start":1,"end":2,"exit":0,"trigger":"custom","status":"ok"}' . "\n");
        file_put_contents(Paths::$oldFlash . '/history/state.json', '{"nightly-backup":{"health":"ok"}}');
        // upstream's schedule.json left behind for rollback must not override the fork's config.json
        file_put_contents(Paths::$oldFlash . '/schedule.json', json_encode([Paths::$oldFlash . '/scripts/nightly-backup/script' => ['frequency' => 'daily']]));
        file_put_contents(Paths::$oldFlash . '/customSchedule.cron', "0 3 * * 1 /usr/local/emhttp/plugins/user.scripts/run.php --script 'nightly-backup' --trigger custom\n");
        mkdir(Paths::$oldTmp . '/history', 0777, true);
        file_put_contents(Paths::$oldTmp . '/history/refresh-ddns.jsonl', '{"start":5,"end":6,"exit":0,"trigger":"custom","status":"ok"}' . "\n");
        file_put_contents(Paths::$oldTmp . '/booted', "booted\n");
        $before = [self::tree(Paths::$oldFlash), self::tree(Paths::$oldTmp)];

        $this->assertSame('imported', Import::fromOld());

        $this->assertSame([self::tree(Paths::$oldFlash), self::tree(Paths::$oldTmp)], $before, 'old dirs untouched');
        $this->assertSame(['nightly-backup', 'refresh-ddns'], Scripts::ids());
        $this->assertSame("#!/bin/bash\necho old\n", file_get_contents(Paths::scripts() . '/nightly-backup/script'));
        $this->assertSame('about nightly-backup', file_get_contents(Paths::scripts() . '/nightly-backup/description'));
        $this->assertSame($cfg, $this->config());
        $this->assertSame(['custom', '0 3 * * 1', 'queue', 21600], [Schedule::get('nightly-backup')['frequency'], Schedule::get('nightly-backup')['custom'], Schedule::get('nightly-backup')['overlap'], Schedule::get('nightly-backup')['timeout']]);
        $this->assertSame(['refresh-ddns', 'nightly-backup'], array_column(Layout::get()['items'], 'id'));
        $s = Settings::get();
        $this->assertSame([150, Paths::$flash . '/history', 30], [$s['historyCap'], $s['historyDir'], $s['syncMinutes']], 'history folder follows the plugin');
        $this->assertFileExists(Paths::$flash . '/history/nightly-backup.jsonl');
        $this->assertFileExists(Paths::$flash . '/history/state.json');
        $this->assertFileExists(Paths::ramHistory() . '/refresh-ddns.jsonl', 'unsynced RAM history comes along');
        $this->assertFileDoesNotExist(Paths::$flash . '/schedule.json');
        $this->assertFileDoesNotExist(Paths::cronFile(), 'our cron file is generated by writeCron, never copied');
        $this->assertStringContainsString('imported', (string)file_get_contents(Paths::$tmp . '/syslog'));
    }

    public function testPoolHistoryDirIsKept(): void
    {
        $this->oldScript('a');
        file_put_contents(Paths::$oldFlash . '/config.json', '{"a":{"frequency":"daily"}}');
        file_put_contents(Paths::$oldFlash . '/settings.json', json_encode(['historyDir' => '/mnt/user/system/user.scripts']));
        Import::fromOld();
        $this->assertSame('/mnt/user/system/user.scripts', json_decode((string)file_get_contents(Paths::settingsFile()), true)['historyDir']);
    }

    public function testUpstreamShapedOldDirMigratesScheduleJsonFromTheOldLocation(): void
    {
        $data = json_decode((string)file_get_contents(__DIR__ . '/fixtures/legacy-schedule.json'), true);
        foreach (array_keys($data) as $path) $this->oldScript(basename(dirname($path)));
        foreach (['ping-hosts', 'refresh-ddns', 'heartbeat', 'sync-photos', 'nightly-backup', 'broken19'] as $id) {
            if (!is_dir(Paths::$oldFlash . "/scripts/$id")) $this->oldScript($id);
        }
        // keys stay as upstream writes them: /boot/config/plugins/user.scripts/scripts/<id>/script
        file_put_contents(Paths::$oldFlash . '/schedule.json', json_encode($data, JSON_UNESCAPED_SLASHES));
        copy(__DIR__ . '/fixtures/legacy-customSchedule.cron', Paths::$oldFlash . '/customSchedule.cron');
        $before = self::tree(Paths::$oldFlash);

        $this->assertSame('imported', Import::fromOld());

        $this->assertSame($before, self::tree(Paths::$oldFlash));
        $this->assertFileExists(Paths::configFile());
        $all = Schedule::all();
        $this->assertSame(count(array_unique(array_merge(array_map(fn($p) => basename(dirname($p)), array_keys($data)), ['broken19']))), count($all));
        $this->assertSame(['custom', '*/5 * * * *'], [$all['refresh-ddns']['frequency'], $all['refresh-ddns']['custom']], 'from a startCustom.php line');
        $this->assertSame(['custom', '* * * * *'], [$all['ping-hosts']['frequency'], $all['ping-hosts']['custom']]);
        foreach ($data as $path => $e) {
            $id = basename(dirname($path));
            if (($e['frequency'] ?? '') !== 'custom' && in_array($e['frequency'] ?? '', ['hourly', 'daily', 'weekly', 'monthly', 'start', 'boot', 'stop'], true)) {
                $this->assertSame($e['frequency'], $all[$id]['frequency'], $id);
            }
        }
    }

    public function testNothingToImport(): void
    {
        $this->assertSame('nothing', Import::fromOld());
        mkdir(Paths::$oldFlash . '/scripts', 0777, true);
        $this->assertSame('nothing', Import::fromOld(), 'an empty old folder');
        $this->assertFileDoesNotExist(Paths::configFile());
        $this->assertSame([], Scripts::ids());
    }

    public function testAlreadyImportedIsANoOp(): void
    {
        $this->oldScript('a');
        file_put_contents(Paths::$oldFlash . '/config.json', '{"a":{"frequency":"daily"}}');
        $this->assertSame('imported', Import::fromOld());
        Schedule::set('a', ['frequency' => 'hourly']);
        file_put_contents(Paths::scripts() . '/a/script', "#!/bin/bash\necho edited\n");
        $this->oldScript('b');
        $cfg = (string)file_get_contents(Paths::configFile());

        $this->assertSame('already', Import::fromOld());

        $this->assertSame($cfg, file_get_contents(Paths::configFile()));
        $this->assertSame("#!/bin/bash\necho edited\n", file_get_contents(Paths::scripts() . '/a/script'));
        $this->assertSame(['a'], Scripts::ids(), 'later changes in the old folder are not merged in');
        $this->assertSame('hourly', Schedule::get('a')['frequency']);
    }

    public function testFailedImportIsRetriedAndNothingWritesConfigMeanwhile(): void
    {
        $this->oldScript('a');
        file_put_contents(Paths::$oldFlash . '/schedule.json', '{broken');
        try { Import::fromOld(); $this->fail('expected the broken schedule file to stop the import'); }
        catch (RuntimeException) {}
        $this->assertTrue(Import::pending());
        $this->assertSame(['disabled'], array_column(Schedule::all(), 'frequency'), 'defaults, nothing scheduled');
        $this->assertFileDoesNotExist(Paths::configFile());
        try { Schedule::set('a', ['frequency' => 'hourly']); $this->fail('edits must wait for the import'); }
        catch (RuntimeException $e) { $this->assertStringContainsString('did not finish', $e->getMessage()); }
        $this->assertFileDoesNotExist(Paths::configFile());

        file_put_contents(Paths::$oldFlash . '/schedule.json', json_encode(['/boot/config/plugins/user.scripts/scripts/a/script' => ['frequency' => 'weekly']]));
        $this->assertSame('imported', Import::fromOld());
        $this->assertFalse(Import::pending());
        $this->assertSame('weekly', Schedule::get('a')['frequency']);
        $this->assertSame('already', Import::fromOld());
    }

    public function testExistingNewScriptsAreNotOverwritten(): void
    {
        $this->makeScript('a', "#!/bin/bash\necho mine\n");
        $this->oldScript('a');
        $this->oldScript('b');
        Import::fromOld();
        $this->assertSame("#!/bin/bash\necho mine\n", file_get_contents(Paths::scripts() . '/a/script'));
        $this->assertSame(['a', 'b'], Scripts::ids());
    }

    public function testBootMarkerIsCarriedSoBootScriptsDoNotRunTwice(): void
    {
        Import::carryBootMarker();
        $this->assertFileDoesNotExist(Paths::$tmp . '/booted');
        mkdir(Paths::$oldTmp, 0777, true);
        file_put_contents(Paths::$oldTmp . '/booted', "booted\n");
        Import::carryBootMarker();
        $this->assertFileExists(Paths::$tmp . '/booted');
        $this->assertFileExists(Paths::$oldTmp . '/booted');
    }

    public function testRunPhpImportCli(): void
    {
        $this->oldScript('a');
        $run = dirname(__DIR__) . '/source/voz.cron/usr/local/emhttp/plugins/voz.cron/run.php';
        $env = 'US_TEST=1 US_FLASH=' . escapeshellarg(Paths::$flash) . ' US_TMP=' . escapeshellarg(Paths::$tmp)
            . ' US_OLD_FLASH=' . escapeshellarg(Paths::$oldFlash) . ' US_OLD_TMP=' . escapeshellarg(Paths::$oldTmp) . ' US_UPDATE_CRON=/bin/true';
        exec("$env php " . escapeshellarg($run) . ' --import 2>&1', $out, $rc);
        $this->assertSame(0, $rc, implode("\n", $out));
        $this->assertStringContainsString('Imported', implode("\n", $out));
        $this->assertSame(['a'], Scripts::ids());
        $this->assertSame('disabled', Schedule::get('a')['frequency']);
        $out = [];
        exec("$env php " . escapeshellarg($run) . ' --import 2>&1', $out, $rc);
        $this->assertSame([0, []], [$rc, $out]);
    }
}
